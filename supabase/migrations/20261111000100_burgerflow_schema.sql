create function public.current_app_user_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select u.id
  from public.users as u
  where u.auth_user_id = (select auth.uid())
    and u.active
  limit 1
$$;

create function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select u.role_id
  from public.users as u
  where u.auth_user_id = (select auth.uid())
    and u.active
  limit 1
$$;

create function public.has_app_permission(permission_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.users as u
    join public.role_permissions as rp on rp.role_id = u.role_id
    where u.auth_user_id = (select auth.uid())
      and u.active
      and rp.permission_id = permission_name
  )
$$;

create function public.can_view_order(target_order_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.orders as o
    where o.id = target_order_id
      and (
        public.has_app_permission('orders:read:all')
        or (public.current_app_role() = 'customer' and o.cliente_id = public.current_app_user_id())
        or (
          public.has_app_permission('orders:kitchen')
          and o.status in ('pending', 'preparing', 'ready')
        )
        or (public.has_app_permission('orders:delivery') and o.repartidor_id = public.current_app_user_id())
      )
  )
$$;

