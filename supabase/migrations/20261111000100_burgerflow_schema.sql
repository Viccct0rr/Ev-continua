  for select to authenticated using (true);

create policy role_permissions_read_authenticated on public.role_permissions
  for select to authenticated using (true);

create policy users_read_self_or_admin on public.users
  for select to authenticated
  using (auth_user_id = (select auth.uid()) or public.has_app_permission('users:manage'));

create policy users_update_admin on public.users
  for update to authenticated
  using (public.has_app_permission('users:manage'))
  with check (public.has_app_permission('users:manage'));

create policy products_read_active on public.products
  for select to anon, authenticated
  using (active or public.has_app_permission('products:write'));

create policy products_insert_admin on public.products
  for insert to authenticated
  with check (public.has_app_permission('products:write'));

create policy products_update_admin on public.products
  for update to authenticated
  using (public.has_app_permission('products:write'))
  with check (public.has_app_permission('products:write'));

create policy inventory_read_admin on public.inventory
  for select to authenticated
  using (public.has_app_permission('inventory:read'));

create policy orders_read_authorized on public.orders
  for select to authenticated
  using (public.can_view_order(id));

