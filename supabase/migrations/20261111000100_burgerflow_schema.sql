create table public.roles (
  id text primary key,
  name text not null unique
);

create table public.permissions (
  id text primary key,
  description text not null
);

create table public.role_permissions (
  role_id text not null references public.roles(id),
  permission_id text not null references public.permissions(id),
  primary key (role_id, permission_id)
);

create table public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete restrict,
  name text not null,
  email text not null,
  role_id text not null references public.roles(id),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index users_email_lower_idx on public.users (lower(email));

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null,
  description text not null default '',
  price_cents bigint not null check (price_cents >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.inventory (
  product_id bigint primary key references public.products(id),
  quantity integer not null check (quantity >= 0),
  unit text not null,
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  code text not null unique,
  created_by bigint not null references public.users(id),
  cliente_id bigint not null references public.users(id),
  repartidor_id bigint references public.users(id),
  order_type text not null check (order_type in ('dine_in', 'pickup', 'delivery')),
  status text not null check (status in ('pending', 'preparing', 'ready', 'out_for_delivery', 'delivered', 'cancelled')),
  created_at timestamptz not null default now(),
  check ((order_type = 'delivery') or repartidor_id is null)
);

create table public.order_financials (
  order_id bigint primary key references public.orders(id),
  subtotal_cents bigint not null check (subtotal_cents >= 0),
  tax_cents bigint not null check (tax_cents >= 0),
  service_cents bigint not null check (service_cents >= 0),
  total_cents bigint not null check (total_cents = subtotal_cents + tax_cents + service_cents)
);

create table public.order_payments (
  order_id bigint primary key references public.orders(id),
  payment_method text not null check (payment_method in ('cash', 'card', 'qr'))
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  product_id bigint not null references public.products(id),
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price_cents bigint not null check (unit_price_cents >= 0),
  line_total_cents bigint not null check (line_total_cents = quantity * unit_price_cents)
);

create table public.personalizations (
  id bigint generated by default as identity primary key,
  order_item_id bigint not null references public.order_items(id) on delete cascade,
  name text not null,
  value text not null,
  price_delta_cents bigint not null default 0 check (price_delta_cents >= 0)
);

create table public.delivery_info (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id),
  customer_name text not null,
  phone text not null,
  address text not null,
  created_at timestamptz not null default now()
);

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  changed_by bigint not null references public.users(id),
  old_status text,
  new_status text not null check (new_status in ('pending', 'preparing', 'ready', 'out_for_delivery', 'delivered', 'cancelled')),
  changed_at timestamptz not null default now()
);

create table public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  changed_by bigint not null references public.users(id),
  delta integer not null check (delta <> 0),
  reason text not null,
  created_at timestamptz not null default now()
);

create index orders_created_by_created_idx on public.orders (created_by, created_at desc);
create index orders_cliente_created_idx on public.orders (cliente_id, created_at desc);
create index orders_status_created_idx on public.orders (status, created_at);
create index orders_repartidor_status_idx on public.orders (repartidor_id, status);
create index order_items_order_idx on public.order_items (order_id);
create index personalizations_order_item_idx on public.personalizations (order_item_id);
create index inventory_movements_product_created_idx on public.inventory_movements (product_id, created_at desc);

