  for select to authenticated
  using (
    public.has_app_permission('orders:read:all')
    or (
      public.current_app_role() = 'customer'
      and exists (
        select 1
        from public.orders as o
        where o.id = order_financials.order_id
          and o.cliente_id = public.current_app_user_id()
      )
    )
  );

